def test_sticky():
    assert m((('!.', 'X', 'Y'), '!.'), ('X', 'X'))
    assert not m((('!.', 'X', 'Y'), '!.'), ('X', 'Y'))
    assert m((('!.', 'X', 'Y'), '!.', ('!.a', 'a', 'b', 'c'), '!.a'), ('X', 'X', 'a', 'a'))
    assert not m((('!.', 'X', 'Y'), '!.', ('!.a', 'a', 'b', 'c'), '!.a'), ('X', 'Y', 'a', 'b'))
    assert m(('_!.', '_!.'), ('X', 'X'))
    assert not m(('_!.', '_!.'), ('X', 'Y'))
    assert m(('_!.', '_!.2', ('!', '_!.', '_!.2')), ('X', 'Y', 'X'))
    assert m(('_!.', '_!.2', ('!', '_!.', '_!.2')), ('X', 'Y', 'Y'))
    assert m(('_!.', '_!.2', ('!', '_!.', '_!.2')), ('X', 'X', 'X'))
    assert not m(('_!.', '_!.2', ('!', '_!.', '_!.2')), ('X', 'Y', 'Z'))
    assert not m(('_!.', ('!', '_!.')), ('X', 'Y'))
    assert m(('_!.', ('!', '_!.')), ('X', 'X'))
