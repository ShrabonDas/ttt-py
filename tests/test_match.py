def test_caret_at():
    assert m(('^@', 'X'), 'X')
    assert m((('^@', 'X'),), ('X',))
    assert not m((('^@', 'X'),), 'X')

    assert m(('^@', ('_*', 'X', '_*'), ('_*', 'Y', '_*'), ('Z',)),
             ('X', ('Y', ('Z',))))

    assert m(('^@', ('_*', 'X', '_*'), ('_*', 'Y', '_*'), ('Z',)),
             ('A', 'B', 'X', 'C', ('D', 'E', 'Y', 'K', ('Z',), 'L'), 'N'))

    assert not m(('^@', ('_*', 'X', '_*', ('_*', 'Y', '_*'), ('Z',))),
                 ('A', 'B', 'X', 'C', ('D', 'E', 'Y', 'K', ('Q', 'Z', 'T'), 'L'), 'N'))

    assert not m(('^@', ('_*', 'X', '_*', ('_*', 'Y', '_*'), ('Z',))),
                 ('A', 'B', 'X', 'C', ('D', 'E', 'Y', 'K', 'Z', 'L'), 'N'))

    assert m(('^@', ('A', ('B', 'C'), 'D'), ('B', 'C'), 'C'),
             ('A', ('B', 'C'), 'D'))
    assert m(('^@', ('+', ('X', '_!', 'Y'))), ('X', 'Z', 'Y'))
    assert m(('^@', ('+', ('X', '_!', 'Y'))), ('X', ('X', 'Z', 'Y'), 'Y'))
    assert m(('^@', ('+', ('X', '_!', 'Y'))), ('X', ('X', ('X', 'Z', 'Y'), 'Y'), 'Y'))

    assert m(('^@',), ())
    assert not m(('^@', '_!'), ())


